class AppLocalizations {
  const AppLocalizations(this.locale);

  final Locale locale;

  static const List<Locale> supportedLocales = <Locale>[
    Locale('en'),
    Locale('es'),
    Locale('pt', 'BR'),
    Locale('fr'),
    Locale('de'),
    Locale('ja'),
    Locale('ko'),
    Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hans'),
    Locale('it'),
    Locale('hi'),
    Locale('ar'),
    Locale('id'),
    Locale('tr'),
    Locale('pl'),
    Locale('nl'),
    Locale('vi'),
    Locale('th'),
    Locale('ru'),
    Locale('sv'),
    Locale('da'),
    Locale('nb'),
  ];

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations) ??
      const AppLocalizations(Locale('en'));

  static Locale? localeForLanguage(AppLanguage language) =>
      language == AppLanguage.system
      ? null
      : supportedLocales.singleWhere(
          (Locale locale) => locale.toLanguageTag() == language.storageName,
        );

  @visibleForTesting
  static Iterable<String> get messageKeys => _catalogs['es']!.keys;

  static AppLocalizations fromLocaleName(String name) {
    final List<String> parts = name.split(RegExp('[_-]'));
    final String language = parts.first;
    final String? script = parts.length > 1 && parts[1].length == 4
        ? parts[1]
        : null;
    final String? country = parts.length > 1 && parts[1].length == 2
        ? parts[1]
        : parts.length > 2
        ? parts[2]
        : null;
    return AppLocalizations(
      Locale.fromSubtags(
        languageCode: language,
        scriptCode: script,
        countryCode: country,
      ),
    );
  }

  String text(String source) {
    final String language = locale.languageCode;
    final String? exact = _catalogs[language]?[source];
    if (exact != null) return exact;
    for (final _TranslationTemplate template
        in _templates[language] ?? const <_TranslationTemplate>[]) {
      final String? result = template.translate(source);
      if (result != null) return result;
    }
    return source;
  }

  static final Map<String, Map<String, String>> _catalogs =
      <String, Map<String, String>>{
        for (int i = 0; i < _translationLanguages.length; i++)
          _translationLanguages[i]: <String, String>{
            for (final MapEntry<String, List<String>> entry
                in _sharedTranslations.entries)
              entry.key: entry.value[i],
            ..._translations[_translationLanguages[i]]!,
          },
      };

  static final Map<String, List<_TranslationTemplate>> _templates =
      <String, List<_TranslationTemplate>>{
        for (final MapEntry<String, Map<String, String>> catalog
            in _catalogs.entries)
          catalog.key:
              <_TranslationTemplate>[
                for (final MapEntry<String, String> entry
                    in catalog.value.entries)
                  if (_TranslationTemplate.tokens.hasMatch(entry.key))
                    _TranslationTemplate(entry.key, entry.value),
              ]..sort(
                (_TranslationTemplate a, _TranslationTemplate b) =>
                    b.literalLength.compareTo(a.literalLength),
              ),
      };
}

class _TranslationTemplate {
  _TranslationTemplate(String source, this.translation)
    : placeholders = tokens
          .allMatches(source)
          .map((RegExpMatch match) => match.group(0)!)
          .toList(),
      literalLength = source.replaceAll(tokens, '').length,
      pattern = RegExp(
        '^${source.splitMapJoin(tokens, onMatch: (_) => '(.*?)', onNonMatch: RegExp.escape)}\$',
        dotAll: true,
      );

  static final RegExp tokens = RegExp(r'\{(\w+)\}');
  final List<String> placeholders;
  final int literalLength;
  final RegExp pattern;
  final String translation;

  String? translate(String source) {
    final RegExpMatch? match = pattern.firstMatch(source);
    if (match == null) return null;
    return translation.replaceAllMapped(tokens, (Match token) {
      final int index = placeholders.indexOf(token.group(0)!);
      return index < 0 ? token.group(0)! : match.group(index + 1)!;
    });
  }
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => AppLocalizations.supportedLocales.any(
    (Locale supported) => supported.languageCode == locale.languageCode,
  );

  @override
  Future<AppLocalizations> load(Locale locale) =>
      SynchronousFuture<AppLocalizations>(AppLocalizations(locale));

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

extension LocalizedString on String {
  String tr(BuildContext context) => AppLocalizations.of(context).text(this);
}

